"""Build lookalikes.tsv: pairs of Core Kanji that look alike, for the
Nihongo::Kanji Look-alikes deck (main.py --seed-lookalikes).

Added 2026-11-14 (user's request: compare learned kanji with similar
radicals and components). Every pair is stored here, for all Core Kanji
rows; the seed only adds a pair once both kanji have been studied on Core
Kanji, so the deck grows as the user learns.

Pairs come from siikamiika/similar-kanji (kanji.tgz_similars.ut8, MIT,
https://github.com/siikamiika/similar-kanji), a hand-made look-alike list
(each line: a kanji and the kanji similar to it); a pair counts if either
kanji lists the other. Both kanji must have a row in kanji_top1000.tsv or
kanji_extra.tsv. Pairs are sorted by the later kanji's position in those
files (study order), so earlier-learned pairs come first.

Columns: a, b (a comes first in the kanji files), same (parts both share),
a_only, b_only (parts only one has). Parts are KRADFILE's (EDRDG, CC BY-SA
4.0), with its stand-ins shown as the real forms (化 -> 亻, 汁 -> 氵 ...);
single strokes (一 丨 ノ 丶 亅 乙) are left out of `same`, since nearly every
kanji has them, and a kanji isn't listed as its own part unless it has no
other. Empty a_only and b_only means the same parts in a
different arrangement (上/下).

Usage:
  python3 tools/add_lookalikes.py           # report what would change
  python3 tools/add_lookalikes.py --write   # rewrite lookalikes.tsv
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_data import fetch, SOURCES  # noqa: E402
from add_radicals import load_json_zip  # noqa: E402  (registers kradfile.zip)

ROOT = Path(__file__).resolve().parent.parent
KANJI_FILES = [ROOT / "kanji_top1000.tsv", ROOT / "kanji_extra.tsv"]
OUT = ROOT / "lookalikes.tsv"
SIMILAR_COMMIT = "0edcfebd5204676dec72b6b12fa26c148489bb1c"
SOURCES.setdefault("similar-kanji.txt", "https://raw.githubusercontent.com/siikamiika/"
                   f"similar-kanji/{SIMILAR_COMMIT}/kanji.tgz_similars.ut8")

# KRADFILE writes some parts with a stand-in kanji.
PART_FORMS = {"化": "亻", "刈": "刂", "忙": "忄", "扎": "扌", "汁": "氵", "杰": "灬",
              "犯": "犭", "礼": "礻", "初": "衤", "込": "辶", "邦": "阝", "阡": "阝",
              "艾": "艹", "老": "耂", "并": "丷", "个": "𠆢", "尚": "⺌", "乞": "𠂉",
              "買": "罒", "疔": "疒", "滴": "啇", "禹": "禸", "｜": "丨"}
STROKES = {"一", "丨", "ノ", "丶", "亅", "乙", "⺄"}

HEADER = """\
# Look-alike kanji pairs for Nihongo::Kanji Look-alikes (python main.py --seed-lookalikes).
# Generated by tools/add_lookalikes.py (2026-11-14); rerun it after adding Core Kanji rows.
# Pairs: siikamiika/similar-kanji (MIT), https://github.com/siikamiika/similar-kanji
# Parts: KRADFILE (c) EDRDG, CC BY-SA 4.0. The seed adds a pair once both kanji are studied.
# Columns: a, b, same (shared parts, single strokes left out), a_only, b_only
#   (empty a_only and b_only: same parts, different arrangement)."""


def kanji_order():
    order = []
    for path in KANJI_FILES:
        for line in path.read_text(encoding="utf-8").split("\n"):
            if line and not line.startswith("#"):
                order.append(line.split("\t")[1])
    return {k: i for i, k in enumerate(order)}


def similar_pairs(known):
    pairs = set()
    with open(fetch("similar-kanji.txt"), encoding="utf-8") as f:
        for line in f:
            items = [x for x in line.strip().split("/") if x]
            for other in items[1:]:
                a, b = items[0], other
                if a != b and a in known and b in known:
                    pairs.add(tuple(sorted((a, b), key=known.get)))
    return sorted(pairs, key=lambda p: (known[p[1]], known[p[0]]))


def parts(k, krad):
    """KRADFILE's parts for `k`, minus `k` itself unless it's the only one
    (KRADFILE lists 日 as a part of 日, and 自 as a part of 自 next to 目)."""
    out = [PART_FORMS.get(p, p) for p in krad.get(k, [])]
    return [p for p in out if p != k] or out


def main(argv):
    known = kanji_order()
    krad = load_json_zip("kradfile.zip")["kanji"]
    rows = []
    for a, b in similar_pairs(known):
        pa, pb = parts(a, krad), parts(b, krad)
        same = [p for p in pa if p in pb and p not in STROKES]
        rows.append([a, b, " ".join(same), " ".join(p for p in pa if p not in pb),
                     " ".join(p for p in pb if p not in pa)])
    text = HEADER + "\n" + "".join("\t".join(r) + "\n" for r in rows)
    old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    print(f"{len(rows)} pairs; lookalikes.tsv "
          f"{'unchanged' if old == text else ('rewritten' if '--write' in argv else 'would change')}.",
          file=sys.stderr)
    if "--write" in argv and old != text:
        OUT.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv[1:])
