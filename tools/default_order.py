#!/usr/bin/env python3
"""Build default_order.tsv: one fixed study order for everyone (the starter deck).

Added 2026-11-17 (user's request: a default order anyone can start from
scratch, even an experienced learner, without touching the user's own
progress). It reads only the data files; it never talks to Anki. The user's
own decks keep using main.py --order, which adapts to their reviews; this is
the frozen order for people who don't run the script (a starter .apkg).

The order, by stage: kana, then N5, N4, N3, unlevelled words, N2, N1, and
last the kanji with no JLPT level. Within a stage:
  - Words (words.tsv order: frequency), Verbs (verbs.tsv order) and Numbers
    & Time (numbers.tsv order) are interleaved in proportion to their counts.
  - Before each of them come the Core Kanji cards it needs and that haven't
    come yet, so a word is never shown before its kanji ("for 学生").
  - Then the stage's remaining kanji, in the kanji files' order (frequency).
  - A Sentences card comes right after the last card it uses; a Look-alikes
    pair right after its second kanji.
Levels: words.tsv `level` (the unlevelled words that open the file,
こんにちは 日本 東京..., count as N5: the file puts them first on purpose); verbs from the JLPT lists in sources/ (and
tools/cache/n3.csv if present), else unlevelled; numbers by their hardest
kanji; kanji by their `jlpt` column. Cards are the ones the seeds make (the
word seed's skips apply: verbs and one-kanji words a kanji card teaches).

Anki keeps one new-card queue per deck, so each deck's cards are studied in
this order among themselves; `pos` is global so the decks line up when the
daily limits keep pace with each other.

Columns: pos, stage, deck (short name), front, why (for a kanji pulled
forward: the card that needed it).

Usage:
  python3 tools/default_order.py           # report the order, write nothing
  python3 tools/default_order.py --write   # (re)write default_order.tsv
"""

import csv
import os
import sys
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import main  # noqa: E402

OUT = os.path.join(ROOT, "default_order.tsv")
LISTS = {"5": os.path.join(ROOT, "sources", "n5.csv"),
         "4": os.path.join(ROOT, "sources", "n4.csv"),
         "3": os.path.join(ROOT, "tools", "cache", "n3.csv")}
STAGES = ["kana", "5", "4", "3", "other", "2", "1", "rest"]
STAGE_NAMES = {"kana": "kana", "5": "N5", "4": "N4", "3": "N3", "other": "unlevelled",
               "2": "N2", "1": "N1", "rest": "kanji, no level"}
SHORT = {main.KANJI_DECK: "Core Kanji", main.WORD_DECK: "Words", main.VERB_DECK: "Verbs",
         main.NUMBER_DECK: "Numbers & Time", main.SENTENCE_DECK: "Sentences",
         main.LOOKALIKE_DECK: "Kanji Look-alikes"}
HEADER = """\
# Default study order for everyone (the starter deck); generated by
# tools/default_order.py from the data files: don't edit by hand, rerun it.
# Not used for the user's own decks (main.py --order adapts to their reviews).
# Columns: pos (global), stage, deck, front, why (a kanji pulled forward: the
#   card that needed it). See the tool's docstring for the rules.
"""


def jlpt_lists():
    """Expression and reading -> easiest JLPT level, from the lists present."""
    level = {}
    for lvl, path in LISTS.items():
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8") as f:
            for r in csv.DictReader(f):
                for key in (r["expression"], r["reading"]):
                    level.setdefault(key, lvl)
    return level


def build():
    kanji = main.core_kanji()                     # file order = frequency order
    kanji_stage = {k: (r["jlpt"] or "rest") for k, r in kanji.items()}
    lists = jlpt_lists()

    def kanji_of(text):
        return [k for k in main._KANJI_CHAR.findall(text) if k in kanji]

    items = {s: [] for s in STAGES}               # stage -> [(deck, front)]
    lead = True                                   # words.tsv opens with greetings on purpose
    for r in main.seeded_words():
        lead = lead and not r["level"]
        stage = r["level"][1:] if r["level"] else ("5" if lead else "other")
        items[stage].append((main.WORD_DECK, r["word"]))
    for r in main.load_verbs():
        lvl = lists.get(r["word"]) or lists.get(r["kana"]) or "other"
        items[lvl].append((main.VERB_DECK, r["word"]))
    for r in main.load_numbers():
        ks = kanji_of(r["front"])
        hardest = min((kanji_stage[k] for k in ks if kanji_stage[k] != "rest"),
                      default="5")
        items[hardest].append((main.NUMBER_DECK, r["front"]))

    # Cards that wait for others: sentences for their words, pairs for their kanji.
    waiting = []
    for r in main.load_sentences():
        waiting.append((main.SENTENCE_DECK, r["japanese"], {f for f, _ in r["words"]}))
    for r in main.load_lookalikes():
        waiting.append((main.LOOKALIKE_DECK, f"{r['a']}・{r['b']}", {r["a"], r["b"]}))
    card_fronts = set(kanji) | {f for s in items.values() for _, f in s}
    waiting = [(d, f, deps & card_fronts) for d, f, deps in waiting]

    order, done = [], set()

    def emit(stage, deck, front, why=""):
        order.append((stage, deck, front, why))
        done.add(front)
        still = []
        for d, f, deps in waiting:
            if deps <= done:
                order.append((stage, d, f, ""))
            else:
                still.append((d, f, deps))
        waiting[:] = still

    for n in main.build_kana_notes():
        emit("kana", n["deckName"].replace(main.DECK_ROOT + "::", ""), n["fields"]["Front"])
    for stage in STAGES[1:]:
        for deck, front in interleave(items[stage]):
            for k in kanji_of(front):
                if k not in done:
                    emit(stage, main.KANJI_DECK, k, f"for {front}")
            emit(stage, deck, front)
        key = stage if stage in ("1", "2", "3", "4", "5") else None
        for k in kanji:
            if k not in done and (kanji_stage[k] == key or
                                  (stage == "rest" and kanji_stage[k] == "rest")):
                emit(stage, main.KANJI_DECK, k)
    left = [(d, f) for d, f, _ in waiting]
    return order, left


def interleave(cards):
    """Mix decks in proportion to their counts, keeping each deck's order."""
    by_deck = {}
    for deck, front in cards:
        by_deck.setdefault(deck, []).append((deck, front))
    queues = [(len(q), q) for q in by_deck.values()]
    out, taken = [], Counter()
    total = sum(n for n, _ in queues)
    for i in range(total):
        # The deck furthest behind its share goes next.
        n, q = min(((n, q) for n, q in queues if taken[id(q)] < n),
                   key=lambda nq: (taken[id(nq[1])] + 1) / nq[0])
        out.append(q[taken[id(q)]])
        taken[id(q)] += 1
    return out


def main_():
    write = "--write" in sys.argv[1:]
    order, left = build()
    fronts = Counter((d, f) for _, d, f, _ in order)
    dupes = [k for k, c in fronts.items() if c > 1]
    if dupes:
        print("Cards placed twice (a bug):", dupes[:10], file=sys.stderr)
        sys.exit(1)

    print(f"{len(order)} cards in the default order.")
    per = Counter((s, SHORT.get(d, d)) for s, d, _, _ in order)
    for stage in STAGES:
        row = {d: n for (s, d), n in per.items() if s == stage}
        if row:
            print(f"  {STAGE_NAMES[stage]:16}", ", ".join(f"{d} {n}" for d, n in sorted(row.items())))
    pulled = sum(1 for *_, why in order if why)
    print(f"  {pulled} kanji come early, right before the first card that uses them.")
    if left:
        print(f"  {len(left)} cards never become ready (they use a card no deck has):",
              " ".join(f for _, f in left[:10]))
    if not os.path.exists(LISTS["3"]):
        print("  (No tools/cache/n3.csv: verbs are levelled by N5/N4 only.)")
    print("\nFirst cards per deck:")
    for deck in SHORT.values():
        first = [f for _, d, f, _ in order if SHORT.get(d, d) == deck][:15]
        if first:
            print(f"  {deck}: {' '.join(first)}")

    if not write:
        print("\nDry run: nothing written. Rerun with --write to save default_order.tsv.")
        return
    with open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write(HEADER)
        f.write("pos\tstage\tdeck\tfront\twhy\n")
        for i, (stage, deck, front, why) in enumerate(order + [("left", d, f, "never ready")
                                                               for d, f in left], 1):
            f.write(f"{i}\t{STAGE_NAMES.get(stage, stage)}\t{SHORT.get(deck, deck)}\t{front}\t{why}\n")
    print(f"\nWrote {os.path.relpath(OUT, ROOT)} ({len(order) + len(left)} rows).")


if __name__ == "__main__":
    main_()
